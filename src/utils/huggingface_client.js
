async function queryHuggingFaceModel(promptText, modelId = "meta-llama/Meta-Llama-3-8B-Instruct") {
  const endpoint = `https://api-inference.huggingface.co/models/${modelId}/v1/chat/completions`;
  const token = "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"; // Your free HF read token

  const response = await fetch(endpoint, {
    method: "POST",
    headers: {
      "Authorization": `Bearer ${token}`,
      "Content-Type": "application/json"
    },
    body: JSON.stringify({
      model: modelId,
      messages: [
        { role: "system", content: "You are an AI operative in the PixelOps secure safehouse network." },
        { role: "user", content: promptText }
      ],
      max_tokens: 300
    })
  });

  const data = await response.json();
  return data.choices[0].message.content;
}
